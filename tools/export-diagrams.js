// T-0120: copy each inline case-study diagram (<div class="dg"><svg>) to projects/<page>/diagrams/<name>.svg,
// so phones can open it full size and pinch-zoom. Re-run after editing a diagram: node tools/export-diagrams.js
// The file is styled by the same CSS as the page (project.css + the page CSS, via xml-stylesheet), so no inline styles.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', 'projects');
let total = 0;
for (const dir of fs.readdirSync(root)) {
  const html = path.join(root, dir, 'index.html');
  if (!fs.existsSync(html)) continue;
  const src = fs.readFileSync(html, 'utf8');
  const css = (src.match(/<link rel="stylesheet" href="([a-z0-9-]+\.css)">/) || [])[1];
  const re = /<span class="dg-hint" id="h-([a-z0-9-]+)">[\s\S]*?<div class="dg"[^>]*>\s*(<svg[\s\S]*?<\/svg>)/g;
  let m, n = 0;
  while ((m = re.exec(src))) {
    const [, name, svg] = m;
    const ids = new Set([...svg.matchAll(/\bid="([^"]+)"/g)].map(x => x[1]));
    for (const [, ref] of svg.matchAll(/url\(#([^)]+)\)/g)) if (!ids.has(ref)) throw new Error(`${dir}/${name}: url(#${ref}) is defined outside the diagram`);
    // XML knows only five named entities; turn the HTML ones into numeric references.
    const ENT = { middot: 183, rarr: 8594, larr: 8592, ndash: 8211, mdash: 8212, hellip: 8230, ldquo: 8220, rdquo: 8221, lsquo: 8216, rsquo: 8217, times: 215, deg: 176, Oslash: 216, nbsp: 160, le: 8804, ge: 8805, asymp: 8776, plusmn: 177, check: 10003 };
    const xml = svg.replace(/&([a-zA-Z]+);/g, (all, k) => { if (/^(amp|lt|gt|quot|apos)$/.test(k)) return all; if (!ENT[k]) throw new Error(`${dir}/${name}: unknown entity &${k};`); return `&#${ENT[k]};`; });
    const body = xml.replace(/^<svg([^>]*)>/, (all, attrs) => `<svg${attrs.replace(/\sclass="[^"]*"/, '')} class="dgfile">\n<g class="dg">`).replace(/<\/svg>$/, '</g>\n</svg>');
    const out = `<?xml version="1.0" encoding="UTF-8"?>\n<?xml-stylesheet type="text/css" href="../../project.css"?>\n` +
      (css ? `<?xml-stylesheet type="text/css" href="../${css}"?>\n` : '') +
      `<?xml-stylesheet type="text/css" href="../../diagram-file.css"?>\n<!-- Generated by tools/export-diagrams.js from ../index.html. Edit the page, then re-run. -->\n${body}\n`;
    fs.mkdirSync(path.join(root, dir, 'diagrams'), { recursive: true });
    fs.writeFileSync(path.join(root, dir, 'diagrams', name + '.svg'), out);
    n++; total++;
  }
  if (n) console.log(`${dir}: ${n} diagram(s)`);
}
console.log('total', total);
